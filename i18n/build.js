// Merges source.es.json + <lang>.json into i18n/strings.js (window.I18N).
const fs = require('fs');
const dir = __dirname;
const es = JSON.parse(fs.readFileSync(dir + '/source.es.json', 'utf8'));
Object.assign(es.static, JSON.parse(fs.readFileSync(dir + '/static-legal.es.json', 'utf8')));
// Strings added after the translation pass
const EXTRA = {
  es:{static:{m139:'¿Ya te has suscrito?'}, ui:{connecting:'Conectando…'}},
  en:{static:{m139:'Already subscribed?'}, ui:{connecting:'Connecting…'}},
  ca:{static:{m139:'Ja t’has subscrit?'}, ui:{connecting:'Connectant…'}},
  pt:{static:{m139:'Já te subscreveste?'}, ui:{connecting:'A ligar…'}},
  de:{static:{m139:'Schon abonniert?'}, ui:{connecting:'Verbinde…'}},
  fr:{static:{m139:'Déjà inscrit·e ?'}, ui:{connecting:'Connexion…'}},
};
const merge = (a, b) => { for (const k in b) a[k] = (b[k] && typeof b[k] === 'object' && !Array.isArray(b[k])) ? merge(a[k] || {}, b[k]) : b[k]; return a; };
const out = {es: merge(JSON.parse(JSON.stringify(es)), EXTRA.es)};
for (const l of ['en', 'ca', 'pt', 'de', 'fr']) {
  const f = `${dir}/${l}.json`;
  if (!fs.existsSync(f)) { console.log('missing', l); continue; }
  out[l] = merge(JSON.parse(fs.readFileSync(f, 'utf8')), EXTRA[l]);
  const lf = `${dir}/legal.${l}.json`;
  if (fs.existsSync(lf)) Object.assign(out[l].static, JSON.parse(fs.readFileSync(lf, 'utf8'))); else console.log('missing legal', l);
}
// Footer link to the terms of sale reuses the legal page's own label
for (const l in out) { const v = out[l].static.l002d; if (v) out[l].static.m140 = out[l].static.c070 = v; }
fs.writeFileSync(dir + '/strings.js', '/* Generated by i18n/build.js — edit i18n/<lang>.json instead */\nwindow.I18N = ' + JSON.stringify(out) + ';\n');
console.log('langs:', Object.keys(out).join(', '), '·', fs.statSync(dir + '/strings.js').size, 'bytes');
